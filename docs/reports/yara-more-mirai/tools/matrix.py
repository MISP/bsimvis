"""Rule x group hit matrix: every rule in rules/*.yar against every family group.

    python3 -I tools/matrix.py   ->  matrix.md (+ matrix.json)
A rule row lists the groups it hits as hits/files. Compare with the rule's own
`family`/`variant`/`capability` meta: a family rule should light its own group
(and siblings by design); a capability rule should light every group that has it.
"""

import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import yc  # noqa: E402

ROOT = os.path.join(yc.HERE, "..")


def split_rules(text):
    parts = re.split(r"(?m)^(?=(?:(?:private|global)\s+)*rule\s+\w+)", text)
    return [p for p in parts if re.match(r"\s*(?:private |global )*rule\s", p)]


def meta_of(block):
    head = block.split("strings:")[0].split("condition:")[0]
    return dict((k, v) for k, _q, v in re.findall(r'(?m)^\s+(\w+)\s*=\s*("?)(.*?)\2\s*$', head))


def main():
    fam = yc.groups()
    targets = [yc.files(fam, i, label=i) for i in fam]
    unclassified = json.load(open(yc.FAMILIES))["unclassified"]
    neg = [{"label": "unclassified", "files": [f"{yc.COLL}:{m}" for m in unclassified]}]
    sizes = {i: len(g["files"]) for i, g in fam.items()}
    rows = []
    for path in sorted(glob.glob(os.path.join(ROOT, "rules", "*.yar"))):
        for block in split_rules(open(path).read()):
            name = re.search(r"rule\s+(\w+)", block).group(1)
            rep = yc.test(block, targets, neg)
            if not rep.get("ok"):
                rows.append({"rule": name, "file": os.path.basename(path), "error": rep})
                continue
            hits = {g["label"]: g["hits"] for g in rep["groups"] if g["role"] == "target" and g["hits"]}
            un = next((g["hits"] for g in rep["groups"] if g["role"] == "negative"), 0)
            m = meta_of(block)
            rows.append(
                {
                    "rule": name,
                    "file": os.path.basename(path),
                    "kind": m.get("kind"),
                    "family": m.get("family"),
                    "variant": m.get("variant") or m.get("capability"),
                    "hits": hits,
                    "unclassified_hits": un,
                    "total": sum(hits.values()) + un,
                }
            )
            print(name, rows[-1]["total"], flush=True)
    json.dump(rows, open(os.path.join(ROOT, "matrix.json"), "w"), indent=1)
    out = ["# Rule x group matrix\n", "hits/files per family group; generated by tools/matrix.py\n"]
    for r in rows:
        if "error" in r:
            out.append(f"- **{r['rule']}** ({r['file']}): ERROR {str(r['error'])[:200]}")
            continue
        cells = ", ".join(f"{g} {n}/{sizes[g]}" for g, n in sorted(r["hits"].items(), key=lambda kv: -kv[1]))
        out.append(
            f"- **{r['rule']}** [{r['kind']}, {r['file']}] -> {cells or 'no hit'}"
            + (f", unclassified {r['unclassified_hits']}" if r["unclassified_hits"] else "")
        )
    open(os.path.join(ROOT, "matrix.md"), "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
